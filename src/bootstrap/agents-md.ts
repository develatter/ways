import type { CheckName } from "../domain/types.js";
import type { Detection } from "../map/detect.js";

/**
 * The AGENTS.md bootstrap writes once: what the project is, the commands ways
 * detected and validated, where the map is, and five lines on working with
 * ways. Nothing an agent finds by reading the code (generated context files
 * that repeat it make agents slower and more expensive; see ADR 0012), and no
 * placeholders to fill: what the human knows and the code does not say, they
 * add themselves, and the onboarder proposes additions in a marked block.
 */
export const PROPOSAL_START = "<!-- ways:onboarder:start (proposed by `ways onboard` from the history, CI and docs; edit or delete freely) -->";
export const PROPOSAL_END = "<!-- ways:onboarder:end -->";

const STACK_NAMES: Record<string, string> = { node: "Node.js/TypeScript", python: "Python", rust: "Rust", go: "Go", java: "Java/JVM" };
const TASK_NAMES: Record<string, string> = { install: "Install", build: "Build", test: "Test", lint: "Lint", typecheck: "Type check", e2e: "End-to-end", run: "Run" };

function words(argv: readonly string[]): string {
  return argv.map((word) => (/^[\w@%+=:,./-]+$/.test(word) ? word : `'${word.replaceAll("'", "'\\''")}'`)).join(" ");
}

export interface AgentsInput {
  detection: Detection;
  /** Checks ways validated by running them (or the human gave), by name. */
  checks: Partial<Record<CheckName, string[]>>;
}

export function renderAgentsMd({ detection, checks }: AgentsInput): string {
  const stacks = detection.stacks.map((stack) => `${STACK_NAMES[stack.id] ?? stack.id} (${stack.tool})`);
  const lines = [
    "# AGENTS.md",
    "",
    "<!-- For coding agents and new contributors. Keep it under 100 lines and about what the code does not say. The layout is MAP.md, generated by `ways map`. -->",
    "",
    "## What this is",
    "",
    `${detection.name}${detection.description ? `: ${detection.description}` : ""}.${stacks.length > 0 ? ` ${stacks.join(", ")}.` : ""} Folders, entry points, tests and CI are in [MAP.md](MAP.md).`,
    "",
    "## Commands",
    "",
    "| Task | Command |",
    "| --- | --- |",
  ];
  const install = detection.commands.find((entry) => entry.task === "install");
  if (install) lines.push(`| ${TASK_NAMES.install} | \`${words(install.argv)}\` |`);
  const names = Object.keys(checks) as CheckName[];
  for (const name of ["build", "test", "lint", "typecheck", "e2e"] as const) {
    const command = checks[name];
    if (command) lines.push(`| ${TASK_NAMES[name]} | \`npx ways run ${name}\` (runs \`${words(command)}\`) |`);
  }
  const start = detection.commands.find((entry) => entry.task === "run");
  if (start) lines.push(`| ${TASK_NAMES.run} | \`${words(start.argv)}\` |`);
  lines.push("");
  lines.push(names.length > 0
    ? "`npx ways run <check>` prints a short summary (each failure on one line, new or already failing at the base) and keeps the full log: `npx ways run --show <id>`. `npx ways run` runs them all."
    : "No check was found that runs: add one with `npx ways check add test -- <command>` (ways runs it once to validate it).");
  lines.push(
    "",
    "## Working with ways",
    "",
    "- Commit as you go; `npx ways done` checks and closes the change. A delivery with acceptance criteria: `npx ways outcome open <id> --goal=\"...\" --criterion=\"AC1:...\" --verify=\"AC1:<command>\"`.",
    "- Run checks with `npx ways run <check>` rather than the raw command: the same run, a summary instead of the whole output.",
    "- Adding tests is free; changing or removing existing tests or checks needs the human's `npx ways approve`. Never weaken a test to pass: `npx ways block \"<what is missing>\"` and stop.",
    "- Learned a durable fact the code does not say? `npx ways remember \"<fact>\" --path=<glob>` and commit it with the change.",
    "- `docs/wiki/`, if there is one, is for people: not your source of truth; your memory is `.ways/knowledge`.",
    "",
  );
  return lines.join("\n");
}

/**
 * AGENTS.md with the onboarder's proposal in its marked block: replaced when
 * the block is there, appended otherwise. Everything else is left byte for
 * byte as the human wrote it.
 */
export function withProposal(current: string, proposal: string): string {
  const body = proposal.trim();
  const block = `${PROPOSAL_START}\n## Conventions and pitfalls\n\n${body.replace(/^##\s+Conventions and pitfalls\s*\n+/i, "")}\n${PROPOSAL_END}`;
  const start = current.indexOf(PROPOSAL_START);
  const end = current.indexOf(PROPOSAL_END);
  if (start >= 0 && end > start) return `${current.slice(0, start)}${block}${current.slice(end + PROPOSAL_END.length)}`;
  return `${current}${current.endsWith("\n") ? "" : "\n"}\n${block}\n`;
}
