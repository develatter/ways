/**
 * 0.3.0-dev.0 → the three layers. In 0.3.0-dev.0 the project map was a
 * `## Map` table inside AGENTS.md, filled in by hand. Now MAP.md is generated
 * and folder purposes live in `.ways/map-notes.json`: the rows a person
 * wrote become notes, the `## Map` section and the template's placeholders
 * leave AGENTS.md, and every other line stays as the person wrote it. An
 * untouched template is replaced by the new AGENTS.md.
 */
const OLD_TEMPLATE = fileURLToPath(new URL("../../assets/upgrade/agents-0.3.md", import.meta.url));
const MAP_LINK = "Folders, entry points, tests and CI are in [MAP.md](MAP.md) (generated by `ways map`).";

/** A template placeholder: a cell or line that is only `(…)`. */
function placeholder(text: string): boolean {
  return /^\(.*\)$/.test(text.trim().replace(/^`|`$/g, ""));
}

export interface SplitAgents {
  agents: string;
  notes: Record<string, string>;
}

/** Moves the `## Map` table out of AGENTS.md into notes and drops the template's placeholder lines; the rest is kept byte for byte. */
export function splitAgents(text: string): SplitAgents {
  const lines = text.split("\n");
  const notes: Record<string, string> = {};
  const out: string[] = [];
  let inMap = false;
  for (const line of lines) {
    if (/^##\s+/.test(line)) {
      inMap = /^##\s+Map\s*$/.test(line);
      if (inMap) {
        out.push("## Where things are", "", MAP_LINK, "");
        continue;
      }
    }
    if (inMap) {
      const row = /^\|\s*`?([^`|]+?)`?\s*\|\s*(.*?)\s*\|\s*$/.exec(line);
      if (row && !/^-+$/.test(row[1]!.trim()) && row[1]!.trim() !== "Path") {
        const path = row[1]!.trim();
        const note = row[2]!.trim();
        // The template's rows start their description with "(…)"; ways' own folder is described by MAP.md itself.
        if (!placeholder(path) && note && !note.startsWith("(") && !path.startsWith(".ways")) notes[path] = note.replace(/\s+/g, " ");
      }
      continue;
    }
    // Template placeholders only: a person's own lines never look like `(…)` alone.
    if (/^\|/.test(line)) {
      const cells = line.split("|").slice(1, -1).map((cell) => cell.trim());
      if (cells.length >= 2 && cells.slice(1).every(placeholder)) continue;
    }
    if (/^-\s+\(.*\)\s*$/.test(line) || (placeholder(line) && line.trim() !== "")) continue;
    if (line.startsWith("<!-- A map of this project for coding agents") && line.includes("Replace the placeholders")) {
      out.push("<!-- For coding agents and new contributors. Keep it under 100 lines and about what the code does not say. The layout is MAP.md, generated by `ways map`. -->");
      continue;
    }
    out.push(line);
  }
  // A table left with only its header, and a heading left with nothing under it, were the template's.
  const kept: string[] = [];
  for (let index = 0; index < out.length; index += 1) {
    const line = out[index]!;
    if (/^\|/.test(line) && /^\|[\s|:-]+\|$/.test(out[index + 1] ?? "") && !/^\|/.test(out[index + 2] ?? "")) {
      index += 1;
      continue;
    }
    kept.push(line);
  }
  const final: string[] = [];
  for (let index = 0; index < kept.length; index += 1) {
    const line = kept[index]!;
    if (/^##\s+/.test(line)) {
      let next = index + 1;
      while (next < kept.length && kept[next]!.trim() === "") next += 1;
      if (next >= kept.length || /^##?\s+/.test(kept[next]!)) {
        index = next - 1;
        continue;
      }
    }
    final.push(line);
  }
  return { agents: final.join("\n").replace(/\n{3,}/g, "\n\n"), notes };
}

export async function migrateLayers(cwd: string, config: HarnessConfig): Promise<{ notes: string[] }> {
  const notes: string[] = [];
  const files = await mapFiles(cwd);
  const detection = detectProject(cwd, files);
  const agentsPath = join(cwd, "AGENTS.md");
  const checks: Partial<Record<CheckName, string[]>> = {};
  for (const name of CHECK_NAMES) {
    const command = config.commands ? config.commands[name] : name === "test" ? config.testCommand : undefined;
    if (command && (config.commands?.required.includes(name) ?? true)) checks[name] = command;
  }
  if (!existsSync(agentsPath) || (await readFile(agentsPath, "utf8")) === await readFile(OLD_TEMPLATE, "utf8")) {
    await writeAtomic(agentsPath, renderAgentsMd({ detection, checks }));
    notes.push("AGENTS.md written from the repository (it was missing or the untouched 0.3 template); MAP.md holds the layout now.");
  } else {
    const current = await readFile(agentsPath, "utf8");
    const split = splitAgents(current);
    if (split.agents !== current) {
      await writeAtomic(agentsPath, split.agents);
      const moved = Object.keys(split.notes);
      if (moved.length > 0) writeMapNotes(cwd, { ...split.notes, ...readMapNotes(cwd) });
      notes.push(`AGENTS.md: the "## Map" table moved to MAP.md${moved.length > 0 ? ` (${moved.length} purpose(s) kept in ${MAP_NOTES_PATH})` : ""} and the template's placeholders removed; your own lines are unchanged.`);
    }
  }
  const checksFile = readChecksFile(cwd);
  let added = false;
  for (const [name, command] of Object.entries(checks) as Array<[CheckName, string[]]>) {
    if (checksFile.checks[name]) continue;
    checksFile.checks[name] = { command, source: "the config before ways upgrade (not run yet)" };
    added = true;
  }
  if (added || !existsSync(join(cwd, CHECKS_PATH))) {
    writeChecksFile(cwd, checksFile);
    notes.push(`${CHECKS_PATH} lists the configured checks; their line base is recorded by \`ways onboard\` or the first \`ways run\` on a clean tree.`);
  }
  const map = join(cwd, MAP_PATH);
  if (!existsSync(map) || readMarker(await readFile(map, "utf8"))) {
    await writeMap(cwd);
    notes.push(`${MAP_PATH} generated from the repository.`);
  } else notes.push(`${MAP_PATH} exists and was not written by ways; it is left as is (rename it to let \`ways map\` generate one).`);
  if (!readOnboarding(cwd)) {
    writeOnboarding(cwd, pendingOnboarding());
    notes.push(`${ONBOARDING_PATH}: pending; the next agent session offers \`ways onboard\` (set "onboarding": "off" in the config to skip it).`);
  }
  return { notes };
}
