import { readFileSync } from "node:fs";
import { join } from "node:path";
import { MAP_NOTES_PATH, MAP_PATH } from "../domain/constants.js";
import { readChecksFile, type ChecksFile } from "../run/checks-file.js";
import { GitRepository } from "../git/git.js";
import { fastHash } from "../runtime/lazy.js";
import { writeFileAtomic } from "../runtime/runtime.js";
import { detectProject, type Detection } from "./detect.js";

/**
 * MAP.md: where things are in the repository, for an agent or a newcomer.
 * The skeleton is derived from the repository alone (no agent): the stacks
 * and commands the manifests and CI define, the folders, entry points, test
 * layout and what is generated. What a folder is *for* cannot be derived;
 * those purposes live in `.ways/map-notes.json` (path → one line), written by
 * the onboarder or a person, and are merged into the table. MAP.md itself is
 * regenerated by `ways map`, so it is never edited by hand.
 *
 * Drift: the marker at the top records the top-level folders and a
 * fingerprint of the stack, commands, entry points, CI and notes. When they
 * no longer match the repository, `ways map --check` fails and the agent's
 * brief says once to run `ways map`. Nothing blocks.
 */
export const MAP_MARKER = "<!-- ways-map ";
const MAX_CHILDREN = 12;
/** Folders that are never worth a row: dependencies, build output, tool caches. */
const NOISE = new Set(["node_modules", ".git", "dist", "build", "target", "coverage", "__pycache__", ".venv", "venv", ".tox", ".next", ".turbo", ".cache", ".pytest_cache", ".mypy_cache", ".ruff_cache"]);

export type MapNotes = Record<string, string>;

export function readMapNotes(top: string): MapNotes {
  try {
    const value: unknown = JSON.parse(readFileSync(join(top, MAP_NOTES_PATH), "utf8"));
    if (!value || typeof value !== "object" || Array.isArray(value)) return {};
    return Object.fromEntries(Object.entries(value).filter((entry): entry is [string, string] => typeof entry[1] === "string" && entry[1].trim() !== "").map(([path, note]) => [normalizeNotePath(path), note.trim().replace(/\s+/g, " ")]));
  } catch {
    return {};
  }
}

/** `src`, `./src/`, `src/` all name the folder `src/`; a file keeps its name. */
export function normalizeNotePath(path: string, folders?: ReadonlySet<string>): string {
  const clean = path.trim().replace(/^\.\//, "").replace(/^\/+/, "");
  if (clean.endsWith("/")) return clean;
  return folders?.has(`${clean}/`) ? `${clean}/` : clean;
}

export function writeMapNotes(top: string, notes: MapNotes): void {
  const sorted = Object.fromEntries(Object.entries(notes).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  writeFileAtomic(join(top, MAP_NOTES_PATH), `${JSON.stringify(sorted, null, 2)}\n`);
}

/** Tracked files and new files that are not ignored: the repository as the map sees it. */
export async function mapFiles(top: string): Promise<string[]> {
  const output = await new GitRepository(top).run(["ls-files", "-z", "--cached", "--others", "--exclude-standard"]);
  return [...new Set(output.split("\0").filter(Boolean))].sort();
}

function folderCounts(files: readonly string[]): Map<string, number> {
  const counts = new Map<string, number>();
  for (const path of files) {
    const segments = path.split("/");
    for (let depth = 1; depth < segments.length; depth += 1) {
      const folder = `${segments.slice(0, depth).join("/")}/`;
      counts.set(folder, (counts.get(folder) ?? 0) + 1);
    }
  }
  return counts;
}

function noisy(folder: string): boolean {
  return folder.split("/").filter(Boolean).some((segment) => NOISE.has(segment));
}

/**
 * Top-level folders, without dependency folders and dot-folders (agent and
 * editor settings, `.ways/` itself) except `.github/`, which holds the CI.
 */
export function topFolders(files: readonly string[]): string[] {
  return [...new Set(files.filter((path) => path.includes("/")).map((path) => `${path.split("/")[0]}/`))].filter((folder) => !noisy(folder) && (!folder.startsWith(".") || folder === ".github/")).sort();
}

export interface MapFacts {
  detection: Detection;
  folders: string[];
  notes: MapNotes;
  /** The checks ways validated by running them (.ways/checks.json): they win over what was only detected. */
  checks: ChecksFile["checks"];
}

/** One command per task: a validated check first, else the detected one. */
export function shownCommands(facts: Pick<MapFacts, "detection" | "checks">): Array<{ task: string; argv: string[]; source: string; validated: boolean }> {
  const checks = facts.checks as Record<string, { command: string[]; source: string } | undefined>;
  const rows: Array<{ task: string; argv: string[]; source: string; validated: boolean }> = facts.detection.commands.map((entry) => {
    const check = checks[entry.task];
    return check ? { task: entry.task, argv: check.command, source: check.source, validated: true } : { task: entry.task, argv: entry.argv, source: entry.source, validated: false };
  });
  for (const [task, check] of Object.entries(checks)) {
    if (check && !rows.some((row) => row.task === task)) rows.push({ task, argv: check.command, source: check.source, validated: true });
  }
  return rows;
}

/** What the drift check compares: everything the map derives except the second-level folders. */
export function fingerprintOf(facts: MapFacts): string {
  const { detection } = facts;
  return fastHash(JSON.stringify([
    facts.folders,
    detection.stacks,
    shownCommands(facts).map((entry) => [entry.task, entry.argv]),
    detection.entryPoints.map((entry) => entry.path),
    detection.ci,
    detection.tests.dirs,
    Object.entries(facts.notes).sort(),
  ])).slice(0, 16);
}

/** Notes keyed as the map shows paths: `api` names the folder `api/` when there is one. */
function notesFor(files: readonly string[], notes: MapNotes): MapNotes {
  const folders = new Set(folderCounts(files).keys());
  return Object.fromEntries(Object.entries(notes).map(([path, note]) => [normalizeNotePath(path, folders), note]));
}

export async function mapFacts(top: string): Promise<MapFacts> {
  const files = await mapFiles(top);
  return { detection: detectProject(top, files), folders: topFolders(files), notes: notesFor(files, readMapNotes(top)), checks: readChecksFile(top).checks };
}

const STACK_NAMES: Record<string, string> = { node: "Node.js/TypeScript", python: "Python", rust: "Rust", go: "Go", java: "Java/JVM" };
const TASK_NAMES: Record<string, string> = { install: "Install", build: "Build", test: "Test", lint: "Lint", typecheck: "Type check", e2e: "End-to-end", run: "Run" };

function code(text: string): string {
  return `\`${text.replaceAll("`", "'")}\``;
}

function words(argv: readonly string[]): string {
  return argv.map((word) => (/^[\w@%+=:,./-]+$/.test(word) ? word : `'${word.replaceAll("'", "'\\''")}'`)).join(" ");
}

/** The rows of the layout table: top-level folders, their children when there are few, and every noted path. */
function layoutRows(files: readonly string[], notes: MapNotes): Array<{ path: string; count: number; note?: string; depth: number }> {
  const counts = folderCounts(files);
  const fileSet = new Set(files);
  const rows = new Map<string, { path: string; count: number; note?: string; depth: number }>();
  const add = (path: string): void => {
    if (rows.has(path)) return;
    const depth = path.replace(/\/$/, "").split("/").length - 1;
    rows.set(path, { path, count: path.endsWith("/") ? counts.get(path) ?? 0 : 1, depth, ...(notes[path] ? { note: notes[path] } : {}) });
  };
  for (const folder of topFolders(files)) {
    add(folder);
    const children = [...counts.keys()].filter((candidate) => candidate.startsWith(folder) && candidate !== folder && candidate.slice(folder.length).split("/").length === 2 && !noisy(candidate));
    if (children.length <= MAX_CHILDREN) for (const child of children) add(child);
  }
  for (const path of Object.keys(notes)) if (counts.has(path) || fileSet.has(path)) add(path);
  return [...rows.values()].sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** Notes whose path is no longer in the repository: reported, never shown in the table. */
export function orphanNotes(files: readonly string[], notes: MapNotes): string[] {
  const counts = folderCounts(files);
  const fileSet = new Set(files);
  return Object.keys(notes).filter((path) => !counts.has(path) && !fileSet.has(path)).sort();
}

export function renderMap(files: readonly string[], facts: MapFacts): string {
  const { detection, notes } = facts;
  const marker = `${MAP_MARKER}${JSON.stringify({ folders: facts.folders, fingerprint: fingerprintOf(facts) })} -->`;
  const lines: string[] = [
    "# MAP.md",
    "",
    marker,
    `<!-- Generated by \`ways map\` from the repository; do not edit it by hand. A folder's purpose comes from ${MAP_NOTES_PATH} (path → one line): edit a note there, then run \`ways map\`. -->`,
    "",
  ];
  const stacks = detection.stacks.map((stack) => `${STACK_NAMES[stack.id] ?? stack.id} (${stack.tool}, ${code(stack.manifest)})`);
  lines.push(`**${detection.name}**${detection.description ? ` — ${detection.description}` : ""}`);
  lines.push("");
  lines.push(stacks.length > 0 ? `Stack: ${stacks.join("; ")}.` : "Stack: not recognised (no package.json, pyproject.toml, requirements.txt, Cargo.toml, go.mod, pom.xml or build.gradle at the root); only the layout is shown.");
  lines.push("", "## Layout", "", "| Path | Files | What lives there |", "| --- | --- | --- |");
  for (const row of layoutRows(files, notes)) {
    const indent = row.depth > 0 ? "&nbsp;&nbsp;".repeat(row.depth) : "";
    lines.push(`| ${indent}${code(row.path)} | ${row.count} | ${row.note ?? ""} |`);
  }
  if (detection.entryPoints.length > 0) {
    lines.push("", "## Entry points", "");
    for (const entry of detection.entryPoints.slice(0, 12)) lines.push(`- ${code(entry.path)} — ${entry.why}`);
  }
  const commands = shownCommands(facts);
  if (commands.length > 0) {
    lines.push("", "## Commands", "", "Run a check with `ways run <check>`: a short summary instead of the whole output, and the full log kept. \"validated\": ways ran it and it works.", "", "| Task | Command | From |", "| --- | --- | --- |");
    for (const entry of commands) lines.push(`| ${TASK_NAMES[entry.task] ?? entry.task} | ${entry.validated ? `\`ways run ${entry.task}\` → ` : ""}${code(words(entry.argv))} | ${entry.source}${entry.validated ? " (validated)" : ""} |`);
  }
  const tests = detection.tests;
  if (tests.count > 0) {
    lines.push("", "## Tests", "");
    lines.push(`- ${tests.count} test file(s)${tests.dirs.length > 0 ? ` in ${tests.dirs.map(code).join(", ")}` : ""}${tests.patterns.length > 0 ? `, named ${tests.patterns.join(", ")}` : ""}.`);
  }
  const generated = detection.ignored.filter((entry) => !entry.includes("*") || entry.endsWith("/")).slice(0, 12);
  if (generated.length > 0 || detection.ci.length > 0) lines.push("", "## Generated, ignored and CI", "");
  if (generated.length > 0) lines.push(`- Ignored by Git (generated or local; do not edit or commit): ${generated.map(code).join(", ")}.`);
  if (detection.ci.length > 0) lines.push(`- CI: ${detection.ci.map(code).join(", ")}.`);
  lines.push("");
  return lines.join("\n");
}

export interface MapMarker {
  folders: string[];
  fingerprint: string;
}

export function readMarker(text: string): MapMarker | undefined {
  const line = text.split("\n").find((candidate) => candidate.startsWith(MAP_MARKER));
  if (!line) return undefined;
  try {
    const value = JSON.parse(line.slice(MAP_MARKER.length).replace(/\s*-->\s*$/, "")) as Partial<MapMarker>;
    return Array.isArray(value.folders) && typeof value.fingerprint === "string" ? { folders: value.folders.filter((folder): folder is string => typeof folder === "string"), fingerprint: value.fingerprint } : undefined;
  } catch {
    return undefined;
  }
}

export interface MapDrift {
  /** Why MAP.md no longer matches: empty when it does. */
  reasons: string[];
  missing: boolean;
}

/** How MAP.md (its marker) differs from the repository as it is now. */
export function mapDrift(current: string | undefined, facts: MapFacts): MapDrift {
  if (current === undefined) return { reasons: [`${MAP_PATH} is missing`], missing: true };
  const marker = readMarker(current);
  if (!marker) return { reasons: [`${MAP_PATH} has no ways marker (written by hand or by an older ways)`], missing: false };
  if (marker.fingerprint === fingerprintOf(facts)) return { reasons: [], missing: false };
  const added = facts.folders.filter((folder) => !marker.folders.includes(folder));
  const removed = marker.folders.filter((folder) => !facts.folders.includes(folder));
  const reasons: string[] = [];
  if (added.length > 0) reasons.push(`new top-level folder(s) ${added.join(", ")}`);
  if (removed.length > 0) reasons.push(`top-level folder(s) gone: ${removed.join(", ")}`);
  if (reasons.length === 0) reasons.push("the stack, commands, entry points, CI or notes changed");
  return { reasons, missing: false };
}

export interface MapResult {
  path: string;
  written: boolean;
  drift: MapDrift;
  orphans: string[];
}

/** `ways map [--check]`: regenerate MAP.md, or only say whether it drifted. */
export async function writeMap(top: string, options: { check?: boolean } = {}): Promise<MapResult> {
  const files = await mapFiles(top);
  const facts: MapFacts = { detection: detectProject(top, files), folders: topFolders(files), notes: notesFor(files, readMapNotes(top)), checks: readChecksFile(top).checks };
  let current: string | undefined;
  try {
    current = readFileSync(join(top, MAP_PATH), "utf8");
  } catch {
    current = undefined;
  }
  const drift = mapDrift(current, facts);
  const orphans = orphanNotes(files, facts.notes);
  if (options.check) return { path: MAP_PATH, written: false, drift, orphans };
  const next = renderMap(files, facts);
  if (next !== current) writeFileAtomic(join(top, MAP_PATH), next);
  return { path: MAP_PATH, written: next !== current, drift: { reasons: [], missing: false }, orphans };
}
