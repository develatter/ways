import { readdir, readFile, rm } from "node:fs/promises";
import { join } from "node:path";
import { KNOWLEDGE_DIR, MANIFEST_PATH } from "../domain/constants.js";
import { writeAtomic } from "../fs/files.js";
import { conceptPaths, inspectOkf, isCurrentConcept, type OkfDocument } from "../knowledge/okf.js";
import { factOf, ordinal } from "./memory.js";

/**
 * Path-scoped rules for Claude Code, derived from the memory: one
 * `.claude/rules/ways-<concept>.md` per current concept with `paths:`. Claude
 * Code loads a rule when it reads or edits a file matching its `paths`, so the
 * memory of an area arrives exactly when the agent works there, with no hook.
 *
 * They are generated, never edited: each starts with a marker naming its
 * concept, `ways remember`, `ways memory index` and adapter installs rewrite
 * them, and only files carrying the marker are ever removed. `ways memory
 * check` warns when they drift from the memory.
 */
export const RULES_DIR = ".claude/rules";
const PREFIX = "ways-";
const MARKER = "<!-- Generated by ways from ";

export interface RuleFile {
  path: string;
  content: string;
}

function ruleName(document: OkfDocument): string {
  return `${PREFIX}${document.id.replace(/[^A-Za-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "").toLowerCase()}.md`;
}

export function renderRule(document: OkfDocument): RuleFile {
  const source = `${KNOWLEDGE_DIR}/${document.path}`;
  const title = typeof document.frontmatter.title === "string" ? document.frontmatter.title : document.id;
  const type = typeof document.frontmatter.type === "string" ? document.frontmatter.type : "concept";
  const fact = factOf(document.body);
  const body = fact.startsWith(title.replace(/…$/, "")) ? fact : `${title}\n${fact}`;
  const content = [
    "---",
    "paths:",
    ...conceptPaths(document).map((glob) => `  - ${JSON.stringify(glob)}`),
    "---",
    `${MARKER}${source}; edit that concept, not this file, and run \`ways memory index\`. -->`,
    "",
    `ways memory (${type}): ${body}`,
    "",
    `Source: ${source}`,
    "",
  ].join("\n");
  return { path: `${RULES_DIR}/${ruleName(document)}`, content };
}

export function renderRules(documents: readonly OkfDocument[]): RuleFile[] {
  return documents.filter((document) => isCurrentConcept(document) && conceptPaths(document).length > 0).map(renderRule).sort((a, b) => ordinal(a.path, b.path));
}

/** Rules are only written where the Claude Code adapter is installed. */
export async function claudeInstalled(cwd: string): Promise<boolean> {
  try {
    const manifest = JSON.parse(await readFile(join(cwd, MANIFEST_PATH), "utf8")) as { adapters?: Record<string, unknown> };
    return Boolean(manifest.adapters?.claude);
  } catch {
    return false;
  }
}

/** Generated rule files currently on disk (those carrying the marker). */
async function generatedOnDisk(cwd: string): Promise<Map<string, string>> {
  const found = new Map<string, string>();
  let names: string[];
  try {
    names = await readdir(join(cwd, RULES_DIR));
  } catch {
    return found;
  }
  for (const name of names.filter((entry) => entry.startsWith(PREFIX) && entry.endsWith(".md"))) {
    const content = await readFile(join(cwd, RULES_DIR, name), "utf8").catch(() => "");
    if (content.includes(MARKER)) found.set(`${RULES_DIR}/${name}`, content);
  }
  return found;
}

export interface RulesDrift {
  /** Rules to write: missing or different from the memory. */
  outdated: string[];
  /** Generated rules whose concept is gone or has no paths any more. */
  orphaned: string[];
}

export async function rulesDrift(cwd: string, documents?: readonly OkfDocument[]): Promise<RulesDrift> {
  const wanted = renderRules(documents ?? (await inspectOkf(cwd, { validateSources: false })).documents);
  const onDisk = await generatedOnDisk(cwd);
  const outdated: string[] = [];
  for (const rule of wanted) {
    const current = onDisk.get(rule.path);
    // A file of the same name without the marker is the user's own: never overwritten.
    if (current === undefined && await readFile(join(cwd, rule.path), "utf8").then(() => true, () => false)) continue;
    if (current !== rule.content) outdated.push(rule.path);
  }
  const names = new Set(wanted.map((rule) => rule.path));
  return { outdated, orphaned: [...onDisk.keys()].filter((path) => !names.has(path)).sort() };
}

/** Writes the rules the memory implies and removes generated ones it no longer does. A no-op without the Claude adapter. */
export async function syncRules(cwd: string, options: { documents?: readonly OkfDocument[]; always?: boolean } = {}): Promise<{ written: string[]; removed: string[] }> {
  if (!options.always && !await claudeInstalled(cwd)) return { written: [], removed: [] };
  const documents = options.documents ?? (await inspectOkf(cwd, { validateSources: false })).documents;
  const wanted = renderRules(documents);
  const drift = await rulesDrift(cwd, documents);
  for (const rule of wanted.filter((entry) => drift.outdated.includes(entry.path))) await writeAtomic(join(cwd, rule.path), rule.content);
  for (const path of drift.orphaned) await rm(join(cwd, path), { force: true });
  return { written: drift.outdated, removed: drift.orphaned };
}
